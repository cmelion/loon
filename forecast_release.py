"""Panel review A1 + A13: forecast-only glider release, and held-out design choice.

A1. The recommended glider (L/D 14 at 20 kg/m^2, crab + speed-to-fly, 100 km
margin) was evaluated with the hindsight release rule ('last': the last hour
any site is reachable). On board, only forecasts exist, so the honest rule is
'causalH': release when a site is reachable now and none is forecast
reachable within the next H hours. For each of the 120 slow-controller tracks
we compute the useful hours over the region before release under each rule,
then the launch-rate-weighted (Little's law) dwell that sets fleet size and
cost, and the Monte Carlo recovery under that rule.

A13. Glider design and margin were chosen and evaluated on the same 120
flights. Here every (design, policy, margin) row of glider_tuning_designs.csv
is ranked on the flights launched on the 1st of each month and evaluated on
the flights launched on the 15th (and the reverse), using the stored
per-flight Monte Carlo recovery probabilities.

Outputs: results/forecast_release.csv, results/forecast_release.md
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import glide_tuning as gt  # noqa: E402

DAYS = np.array([31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31])
POLICIES = [('last', 100.0), ('causal24', 100.0), ('causal72', 100.0), ('causal120', 100.0), ('causal168', 100.0)]


def littles(days_by_flight, months):
  s = pd.Series(days_by_flight).groupby(pd.Series(months)).mean()
  d = DAYS[s.index.values - 1]
  return d.sum() / (d / s.values).sum()


def a1():
  table = pd.read_csv('results/glider_tuning_design_table.csv')
  rec = table[(table.ld == 14.0) & (table.wing_kg_m2 == 20.0)].iloc[0]
  design = dict(ld=14.0, sink_sl=float(rec.sink_sl))
  bg, tr = gt._setup()
  r = gt.nominal_margins(bg, tr, design, 'crab', True)
  mats = gt.margin_matrix(tr, r)
  months = {f: int(f.split('_')[1].split('-')[1]) for f in tr.flights}
  full = {f: tr.dwell[f] / 24 for f in tr.flights}
  rows, out = [], {}
  for pol, m in POLICIES:
    rel = gt.releases(tr, mats[0], pol, m)
    mc = gt.mc_eval(bg, tr, rel, design, 'crab', True)
    rec_p = dict(zip(mc['flights'], mc['reached'].mean(axis=1)))
    useful = {}
    for f in tr.flights:
      useful[f] = (tr.df.h.values[rel[f][0]] / 24) if rel[f] is not None else full[f]
    fl = tr.flights
    out[pol] = useful
    rows.append(dict(
        policy=f'{pol}-{m:g}',
        recovered=np.mean([rec_p.get(f, 0.0) for f in fl]),
        useful_days_mean=np.mean([useful[f] for f in fl]),
        useful_days_littles=littles([useful[f] for f in fl], [months[f] for f in fl]),
        full_dwell_littles=littles([full[f] for f in fl], [months[f] for f in fl]),
        lost_h_mean=np.mean([24 * (full[f] - useful[f]) for f in fl])))
  t = pd.DataFrame(rows)
  t['launch_multiplier_vs_hindsight'] = (t.useful_days_littles.iloc[0] / t.useful_days_littles)
  return t


def a13():
  d = pd.read_csv('results/glider_tuning_designs.csv')
  d = d[d.policy.isin(['last', 'causal24', 'causal72'])].copy()
  d['p'] = d.p_flight.apply(
      lambda v: {k: float(x) for k, x in (kv.split('=') for kv in str(v).split(';') if '=' in kv)})
  res = []
  for train_day, test_day in (('01', '15'), ('15', '01')):
    def score(pf, day):
      v = [p for f, p in pf.items() if f.split('_')[1].endswith('-' + day)]
      n_all = 60  # flights launched on that day (5 sites x 12 months); missing = not released = lost
      return sum(v) / n_all
    d['train'] = d.p.apply(lambda pf: score(pf, train_day))
    d['test'] = d.p.apply(lambda pf: score(pf, test_day))
    for pol in ('last', 'causal24', 'causal72'):
      sub = d[d.policy == pol]
      best = sub.sort_values(['train', 'lost_h_mean'], ascending=[False, True]).iloc[0]
      res.append(dict(train_on=train_day, test_on=test_day, policy=pol, ld=best.ld,
                      wing_kg_m2=round(best.wing_kg_m2, 1), margin=best.margin,
                      train_rec=best.train, test_rec=best.test))
  return pd.DataFrame(res)


def main():
  t1 = a1()
  t2 = a13()
  pd.set_option('display.width', 200)
  print(t1.round(3).to_string(index=False))
  print()
  print(t2.round(3).to_string(index=False))
  t1.to_csv('results/forecast_release.csv', index=False)
  with open('results/forecast_release.md', 'w') as f:
    f.write('# Forecast-only glider release and held-out design choice\n\n')
    f.write('Generated by `forecast_release.py` (panel review items A1 and A13).\n\n')
    f.write('## A1: release rule vs useful dwell and recovery (L/D 14, 20 kg/m², 100 km margin)\n\n')
    f.write(t1.round(3).to_markdown(index=False) + '\n\n')
    f.write('## A13: design chosen on one launch day, evaluated on the other\n\n')
    f.write(t2.round(3).to_markdown(index=False) + '\n')


if __name__ == '__main__':
  main()
