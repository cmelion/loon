"""Panel review A3: does the radio glider survive real low-level winds (the jet)?

Same 120 slow-controller tracks, same release rules and wind-error Monte Carlo
as glide_tuning.py, under three wind fields:
  gfs_taper    Open-Meteo GFS 150-30 hPa, 150 hPa wind tapered to the surface
               (what the article's 98% used)
  ncep_taper   NCEP/NCAR Reanalysis-1 150-30 hPa, same taper (dataset control)
  ncep_full    NCEP/NCAR Reanalysis-1 1000-30 hPa: real winds all the way down,
               including the 8-12 km jet
The ncep_taper -> ncep_full change isolates the effect of the missing
low-level winds. Designs: the article's (L/D 14, 20 kg/m^2) and the held-out
winner (L/D 18, 45 kg/m^2). Releases: hindsight and 5-day forecast lookahead.

Output: results/jet_test.csv, results/jet_test.md
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import glide_batch as gb  # noqa: E402
import glide_tuning as gt  # noqa: E402
from europe_ble import WindGrid  # noqa: E402

GRIDS = {'gfs_taper': 'data/gfs_europe_2025.npz',
         'ncep_taper': 'data/ncep_europe_upper_2025.npz',
         'ncep_full': 'data/ncep_europe_full_2025.npz',
         'era5_taper': 'data/era5_europe_upper_2025.npz',
         'era5_full': 'data/era5_europe_2025.npz'}
POLICIES = [('last', 100.0), ('causal120', 100.0)]


def designs():
  t = pd.read_csv('results/glider_tuning_design_table.csv')
  out = []
  for ld, wl in ((14.0, 20.0), (18.0, 45.0)):
    r = t[(t.ld == ld) & (t.wing_kg_m2 == wl)].iloc[0]
    out.append((f'L/D {ld:g} @ {wl:g} kg/m2', dict(ld=ld, sink_sl=float(r.sink_sl))))
  return out


def main():
  tr = gt.Tracks()
  rows = []
  for gname, path in GRIDS.items():
    bg = gb.BatchGrid(WindGrid(path))
    for dname, design in designs():
      r = gt.nominal_margins(bg, tr, design, 'crab', True)
      mats = gt.margin_matrix(tr, r)
      for pol, m in POLICIES:
        rel = gt.releases(tr, mats[0], pol, m)
        mc = gt.mc_eval(bg, tr, rel, design, 'crab', True)
        s = gt.summarise(tr, rel, mats, mc, f'{pol}-{m:g}')
        rows.append(dict(winds=gname, design=dname, policy=f'{pol}-{m:g}',
                         recovered=s['mc_rec'], p10=s['mc_p10'], p90=s['mc_p90'],
                         nominal=s['nominal_rec'], glide_h_med=s['glide_h_med'],
                         ground_km_med=s['ground_med'], lost_h_mean=s['lost_h_mean']))
        print(rows[-1], flush=True)
  t = pd.DataFrame(rows)
  t.to_csv('results/jet_test.csv', index=False)
  piv = t.pivot_table(index=['design', 'policy'], columns='winds', values='recovered')
  piv = piv[list(GRIDS)]
  piv['full_minus_taper'] = piv.ncep_full - piv.ncep_taper
  with open('results/jet_test.md', 'w') as f:
    f.write('# Glider recovery with real low-level winds (panel review A3)\n\n')
    f.write('Generated by `jet_test.py`. Monte Carlo recovery (40 wind-error samples '
            'per release, 120 tracks).\n\n')
    f.write(piv.round(3).to_markdown() + '\n\n')
    f.write(t.round(3).to_markdown(index=False) + '\n')
  pd.set_option('display.width', 200)
  print(piv.round(3).to_string())


if __name__ == '__main__':
  main()
